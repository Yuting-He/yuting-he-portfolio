function resolvedLanguage(language) {
  return SUPPORTED_LANGUAGES.includes(language) ? language : "en";
}

export function textFor(language, key, values = {}) {
  const locale = resolvedLanguage(language);
  const template = COPY[locale][key] ?? COPY.en[key] ?? key;
  return Object.entries(values).reduce(
    (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
    template
  );
}

export function profileLabel(language, group, key, fallback = key) {
  const locale = resolvedLanguage(language);
  return PROFILE_LABELS[locale]?.[group]?.[key] ?? PROFILE_LABELS.en?.[group]?.[key] ?? fallback;
}

export function severityLabel(language, level) {
  const locale = resolvedLanguage(language);
  return SEVERITY_LABELS[locale][level?.className] ?? level?.label ?? SEVERITY_LABELS[locale].unavailable;
}

export function confidenceLabel(language, confidence) {
  const locale = resolvedLanguage(language);
  return CONFIDENCE_LABELS[locale][confidence?.className] ?? confidence?.label ?? "";
}

export function applyDocumentLanguage(document, language) {
  const locale = resolvedLanguage(language);
  document.documentElement.lang = locale;
  document.title = textFor(locale, "pageTitle");
  const description = document.querySelector('meta[name="description"]');
  if (description) description.content = textFor(locale, "pageDescription");
  const ogTitle = document.querySelector('meta[property="og:title"]');
  if (ogTitle) ogTitle.content = textFor(locale, "pageTitle");
  const ogDescription = document.querySelector('meta[property="og:description"]');
  if (ogDescription) ogDescription.content = textFor(locale, "pageDescription");
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    element.textContent = textFor(locale, element.dataset.i18n);
  });
  document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
    element.setAttribute("aria-label", textFor(locale, element.dataset.i18nAriaLabel));
  });
  document.querySelectorAll("[data-warning-link]").forEach((link) => {
    link.href = locale === "de"
      ? "https://www.dwd.de/DE/wetter/warnungen_aktuell/warnungen_aktuell_node.html"
      : "https://www.dwd.de/EN/weather/warnings/warnings_node.html";
  });
}
